import path from 'node:path'
import { defineConfig } from 'vite'
import solidPlugin from 'vite-plugin-solid'

/**
 * The game runs on the website's 2D engine (`apps/web/src/engine`, the one the
 * header is drawn with) and its runner sprites, imported straight from the web
 * app. Those files import each other through `@/`, so `@/` here means the web
 * app's `src`, and this app's own files import each other relatively.
 */
const web = path.resolve(__dirname, '../web/src')

export default defineConfig({
	base: '/run/',
	plugins: [solidPlugin()],
	server: {
		port: 3011,
	},
	build: {
		target: 'esnext',
	},
	resolve: {
		alias: [
			// Seasons glob every PNG the website has to find their Halloween and
			// snow variants. The game has no seasons yet, so it gets a stand-in.
			{
				find: /^@\/utils\/seasons$/,
				replacement: path.resolve(__dirname, 'src/shims/seasons.ts'),
			},
			{ find: /^@\//, replacement: `${web}/` },
			// The engine's styles, generated by this app's own Panda config.
			{
				find: /^@style\//,
				replacement: `${path.resolve(__dirname, 'styled-system')}/`,
			},
			{
				find: /^@shared\//,
				replacement: `${path.resolve(__dirname, '../../libs/shared')}/`,
			},
		],
	},
})
