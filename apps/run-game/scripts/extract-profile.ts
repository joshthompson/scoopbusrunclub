/**
 * Turns a course's GPX into the elevation profile its level's hills are built
 * from: one height every `STEP_M` metres along the course, smoothed, written
 * out as a TypeScript module next to the level.
 *
 * The GPX files live in `apps/game/gpx`, which isn't committed, so the profile
 * is generated once here and the output is committed instead.
 *
 * Usage: pnpm --filter @scoopbus/run-game extract-profile haga
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const STEP_M = 10
/** Watch altitude moves in 0.2 m steps; averaging over this many metres either side smooths them out. */
const SMOOTH_M = 40

const level = process.argv[2] ?? 'haga'
const gpxFile = process.argv[3] ?? `${level}-alt.gpx`
const gpx = readFileSync(
	path.resolve(import.meta.dirname, '../../game/gpx', gpxFile),
	'utf8',
)

const points = [
	...gpx.matchAll(
		/<trkpt lat="([\d.-]+)" lon="([\d.-]+)">[\s\S]*?<ele>([\d.-]+)<\/ele>/g,
	),
].map(([, lat, lon, ele]) => ({ lat: +lat, lon: +lon, ele: +ele }))

function metresBetween(
	a: { lat: number; lon: number },
	b: { lat: number; lon: number },
) {
	const R = 6371000
	const toRad = (d: number) => (d * Math.PI) / 180
	const dLat = toRad(b.lat - a.lat)
	const dLon = toRad(b.lon - a.lon)
	const h =
		Math.sin(dLat / 2) ** 2 +
		Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLon / 2) ** 2
	return 2 * R * Math.asin(Math.sqrt(h))
}

let distance = 0
const along = points.map((p, i) => {
	if (i > 0) distance += metresBetween(points[i - 1], p)
	return { d: distance, ele: p.ele }
})

/** Elevation at `d` metres along, interpolated between the GPX points either side. */
function elevationAt(d: number) {
	const i = along.findIndex((p) => p.d >= d)
	if (i <= 0) return along[i === 0 ? 0 : along.length - 1].ele
	const a = along[i - 1]
	const b = along[i]
	const t = (d - a.d) / (b.d - a.d || 1)
	return a.ele + (b.ele - a.ele) * t
}

const raw: number[] = []
for (let d = 0; d <= distance; d += STEP_M) raw.push(elevationAt(d))

const reach = SMOOTH_M / STEP_M
const smoothed = raw.map((_, i) => {
	const window = raw.slice(Math.max(0, i - reach), i + reach + 1)
	return window.reduce((sum, e) => sum + e, 0) / window.length
})
const lowest = Math.min(...smoothed)
const heights = smoothed.map((e) => Math.round((e - lowest) * 10) / 10)

const out = `// Generated by scripts/extract-profile.ts from ${gpxFile}. Re-run it rather than editing by hand.

/** Metres between each height in \`heights\`. */
export const STEP_M = ${STEP_M}

/** Height above the lowest point of the course, in metres, every \`STEP_M\` metres from the start. */
export const heights = [${heights.join(', ')}]
`

const outFile = path.resolve(
	import.meta.dirname,
	`../src/levels/${level}-profile.ts`,
)
writeFileSync(outFile, out)
console.log(
	`${points.length} points, ${(distance / 1000).toFixed(2)} km, ${heights.length} heights, climb range ${Math.max(...heights)} m → ${path.relative(process.cwd(), outFile)}`,
)
